const fs=require('node:fs'),assert=require('node:assert/strict'),ts=require('typescript');
require.extensions['.ts']=(module,file)=>module._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,file);
const {moveSelectionOnPage,dropSelectionOnPage,removeAndRenumber}=require('../lib/balloons.ts');
const {coordinatePoint,coordinateFromCell,defaultCoordinateTable}=require('../lib/tables.ts');
const make=(id,number,page=1)=>({id,number:String(number),page,coordinate:{point:'Punto '+id,axis:'X',value:''},crop:'recorte-'+id});
const zones=['a','b','c','d','e'].map((id,i)=>make(id,i+1));const other=make('other',201,2),all=[...zones,other];
const single=moveSelectionOnPage(all,1,['c'],1);
assert.deepEqual(single.map(z=>z.id),['c','a','b','d','e','other']);
assert.deepEqual(single.map(z=>z.number),['1','2','3','4','5','201']);
assert.equal(single[0].coordinate.point,'Punto c');assert.equal(single[0].crop,'recorte-c');assert.equal(single[5],other);
const block=moveSelectionOnPage(all,1,['e','c'],1);
assert.deepEqual(block.map(z=>z.id),['c','e','a','b','d','other']);
assert.deepEqual(block.slice(0,5).map(z=>z.number),['1','2','3','4','5']);
const dropped=dropSelectionOnPage(all,1,['b','d'],'e',true);
assert.deepEqual(dropped.map(z=>z.id),['a','c','e','b','d','other']);
assert.deepEqual(dropSelectionOnPage(all,1,['d','e'],'a',false).map(z=>z.id),['d','e','a','b','c','other']);
assert.equal(dropSelectionOnPage(all,1,['b','d'],'b',true),all);
assert.equal(moveSelectionOnPage(all,1,['unknown'],2),all);
assert.equal(moveSelectionOnPage(all,1,['b'],0),all);
const twenty=Array.from({length:20},(_,i)=>make('id-'+(i+1),i+1));
const removed=removeAndRenumber([...twenty,other],['id-17'],{1:'21',2:'202'});
assert.equal(removed.zones.find(z=>z.id==='id-16').number,'16');
assert.equal(removed.zones.find(z=>z.id==='id-18').number,'17');
assert.equal(removed.zones.find(z=>z.id==='id-19').number,'18');
assert.equal(removed.zones.find(z=>z.id==='id-20').number,'19');
assert.equal(removed.nextNumbers[1],'20');assert.equal(removed.nextNumbers[2],'202');assert.equal(removed.zones.at(-1),other);
const bulk=removeAndRenumber(all,['b','d'],{1:'6',2:'202'});
assert.deepEqual(bulk.zones.map(z=>[z.id,z.number]),[['a','1'],['c','2'],['e','3'],['other','201']]);
assert.equal(bulk.nextNumbers[1],'4');assert.deepEqual(zones.map(z=>z.number),['1','2','3','4','5']);
const empty=removeAndRenumber(all,zones.map(z=>z.id),{1:'6',2:'202'});
assert.deepEqual(empty.zones,[other]);assert.equal(empty.nextNumbers[1],'1');
const decimals=['101.1','101.2','101.3','101.4'].map((number,i)=>make('decimal-'+i,number));
const decimalDelete=removeAndRenumber(decimals,['decimal-1']);
assert.deepEqual(decimalDelete.zones.map(z=>z.number),['101.1','101.2','101.3']);assert.equal(decimalDelete.nextNumbers[1],'101.4');
const table=structuredClone(defaultCoordinateTable),cell={tableId:table.id,row:0,column:2,value:''};
const named=coordinatePoint([table],cell,' P12 ');
assert.equal(named.cell.row,3);assert.equal(named.tables[0].rows[3],'P12');assert.equal(table.rows.length,3);
assert.deepEqual(coordinateFromCell(named.cell,named.tables),{point:'P12',axis:'Z',value:''});
const existing=coordinatePoint(named.tables,named.cell,'Punto B');
assert.equal(existing.cell.row,1);assert.equal(existing.tables[0].rows.length,4);
assert.throws(()=>coordinatePoint([table],cell,''));
assert.throws(()=>coordinatePoint([table],cell,'x'.repeat(101)));
